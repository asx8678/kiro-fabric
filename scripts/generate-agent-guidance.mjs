import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const GUIDANCE_FILES = Object.freeze({
  skill: "skills/fabric-exec/SKILL.md",
  guide: "skills/fabric-exec/references/api.md",
  recipes: "skills/fabric-exec/references/recipes.md",
  workflow: "skills/fabric-exec/references/workflow.md",
  review: "skills/fabric-exec/references/review.md",
});

/** @param {string} root */
export function renderAgentGuidance(root) {
  const entries = Object.entries(GUIDANCE_FILES).map(([topic, relative]) => {
    const file = path.join(root, relative);
    const bytes = fs.readFileSync(file);
    const text = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(bytes);
    if (!text.trim() || text.includes("\0") || text.length > 100000) throw new Error(`Invalid or unpageable bundled guidance: ${relative}`);
    return [topic, text];
  });
  return "// Generated by scripts/generate-agent-guidance.mjs from canonical Markdown.\n" +
    "export const BUNDLED_GUIDANCE = Object.freeze(" + JSON.stringify(Object.fromEntries(entries), null, 2) + " as const);\n";
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = path.join(root, "src/kiro/generated-guidance.ts");
  const rendered = renderAgentGuidance(root);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== rendered) throw new Error("Bundled guidance is stale; run pnpm run build and include the generated source");
  } else if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== rendered) {
    fs.writeFileSync(target, rendered);
  }
}
